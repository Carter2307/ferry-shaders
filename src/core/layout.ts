import { TRANSPARENT } from './color'
import type { FrameUniforms, ParamSchema, Rgba, ShaderDefinition } from './types'

/** Size of the fixed header of the uniform buffer, in bytes. The parameters come after it. */
export const HEADER_BYTES = 48

/**
 * Names of the header fields of the `Uniforms` struct. A parameter cannot take one of them.
 * `_pad0` and `_pad1` only fill the gaps WGSL alignment asks for.
 */
export const HEADER_FIELDS = ['resolution', 'mouse', 'time', 'amount', 'pixelRatio', '_pad0', 'focus', '_pad1'] as const

/** How the parameters of one schema are laid out in the uniform buffer. */
export interface UniformLayout {
  /**
   * The generated WGSL header: the `Uniforms` struct, its binding (`u`, group 0, binding 0) and the
   * vertex stage (`vs_main`, one triangle that covers the canvas).
   */
  wgsl: string
  /** Size of the uniform buffer in bytes: a multiple of 16. */
  byteSize: number
  /** Offset of every parameter in the buffer, in bytes, by key. */
  offsets: Readonly<Record<string, number>>
}

const HEADER_WGSL = `  resolution: vec2f, // canvas size, in canvas pixels (grid cells or device pixels)
  mouse: vec2f,      // pointer position, in canvas pixels, origin bottom-left
  time: f32,         // seconds, already multiplied by the speed
  amount: f32,       // pointer influence, 0..1
  pixelRatio: f32,   // canvas pixels per CSS pixel
  _pad0: f32,
  focus: vec2f,      // calm column [left, right], in canvas pixels; left >= right means none
  _pad1: vec2f,`

const VERTEX_WGSL = `@group(0) @binding(0) var<uniform> u: Uniforms;

@vertex
fn vs_main(@builtin(vertex_index) index: u32) -> @builtin(position) vec4f {
  // One oversized triangle covers the whole canvas.
  var positions = array<vec2f, 3>(vec2f(-1.0, -1.0), vec2f(3.0, -1.0), vec2f(-1.0, 3.0));
  return vec4f(positions[index], 0.0, 1.0);
}
`

/**
 * Builds the uniform layout of a schema and the WGSL header that declares it.
 *
 * After the 48-byte header come the color parameters (`vec4f`, 16 bytes each, in schema order),
 * then every other parameter (`f32`, 4 bytes each, in schema order). Colors go first because a
 * `vec4f` must start on a multiple of 16 bytes: this order needs no padding.
 */
export function buildLayout(schema: ParamSchema): UniformLayout {
  const entries = Object.entries(schema)
  const colors = entries.filter(([, def]) => def.type === 'color')
  const scalars = entries.filter(([, def]) => def.type !== 'color')

  const offsets: Record<string, number> = {}
  const members: string[] = []
  let offset = HEADER_BYTES
  for (const [key] of colors) {
    offsets[key] = offset
    offset += 16
    members.push(`  ${key}: vec4f,`)
  }
  for (const [key] of scalars) {
    offsets[key] = offset
    offset += 4
    members.push(`  ${key}: f32,`)
  }

  const struct = ['struct Uniforms {', HEADER_WGSL, ...members, '}'].join('\n')
  return {
    wgsl: `// Generated by ferry-shaders from the parameter schema.\n${struct}\n\n${VERTEX_WGSL}`,
    // A buffer may be larger than the struct it backs: 16 is a multiple of every WGSL alignment.
    byteSize: Math.ceil(offset / 16) * 16,
    offsets,
  }
}

/** Layouts are derived from the definition alone: build each one once. */
const layouts = new WeakMap<ShaderDefinition, UniformLayout>()

/** The uniform layout of a shader (built on first use, then reused). */
export function shaderLayout(shader: ShaderDefinition): UniformLayout {
  let layout = layouts.get(shader)
  if (!layout) {
    layout = buildLayout(shader.params)
    layouts.set(shader, layout)
  }
  return layout
}

/** The complete WGSL module of a shader: the generated header, then its fragment code. */
export function shaderSource(shader: ShaderDefinition): string {
  return `${shaderLayout(shader).wgsl}\n${shader.fragment}`
}

/**
 * Writes the parameters into `target` (the uniform buffer as 32-bit floats) at their offsets.
 *
 * `values` are the sanitised values (`resolveParams`) and `colors` the resolved colors
 * (`resolveColors`). A boolean is written as 0 or 1, a select as the index of its option.
 * The header is left as it is: {@link writeFrame} fills it.
 */
export function packParams(
  layout: UniformLayout,
  schema: ParamSchema,
  values: Readonly<Record<string, unknown>>,
  colors: Readonly<Record<string, Rgba>>,
  target: Float32Array,
): void {
  for (const [key, def] of Object.entries(schema)) {
    const offset = layout.offsets[key]
    if (offset === undefined) continue
    const index = offset / 4
    const value = values[key]
    switch (def.type) {
      case 'color':
        target.set(colors[key] ?? TRANSPARENT, index)
        break
      case 'number':
        target[index] = typeof value === 'number' && Number.isFinite(value) ? value : def.default
        break
      case 'boolean':
        target[index] = (typeof value === 'boolean' ? value : def.default) ? 1 : 0
        break
      case 'select':
        // An unknown value reads as the first option, the same as index 0 in the shader.
        target[index] = Math.max(
          0,
          def.options.findIndex((option) => option.value === value),
        )
        break
    }
  }
}

/** Writes the values of one frame into the header of `target` (the first 48 bytes). */
export function writeFrame(target: Float32Array, frame: FrameUniforms): void {
  target[0] = frame.resolution[0]
  target[1] = frame.resolution[1]
  target[2] = frame.mouse[0]
  target[3] = frame.mouse[1]
  target[4] = frame.time
  target[5] = frame.amount
  target[6] = frame.pixelRatio
  target[7] = 0
  target[8] = frame.focus[0]
  target[9] = frame.focus[1]
  target[10] = 0
  target[11] = 0
}
